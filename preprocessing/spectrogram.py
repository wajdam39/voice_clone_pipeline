"""Mel-spectrogram feature extraction."""

from __future__ import annotations

import numpy as np


def audio_to_melspectrogram(
    waveform: np.ndarray,
    sample_rate: int,
    n_fft: int = 1024,
    hop_length: int = 256,
    win_length: int = 1024,
    n_mels: int = 80,
    f_min: float = 0.0,
    f_max: float | None = 8000.0,
) -> np.ndarray:
    """Convert a waveform into a log-scaled mel-spectrogram.

    Args:
        waveform: 1-D numpy array of audio samples.
        sample_rate: Sample rate of ``waveform``.
        n_fft: FFT window size.
        hop_length: Number of samples between successive frames.
        win_length: Window length for STFT.
        n_mels: Number of mel filterbank channels.
        f_min: Minimum frequency for mel filterbank.
        f_max: Maximum frequency for mel filterbank.

    Returns:
        A 2-D numpy array of shape (n_mels, n_frames) containing the
        log-scaled mel-spectrogram (natural log, with a small epsilon floor).
    """
    import librosa

    mel = librosa.feature.melspectrogram(
        y=waveform,
        sr=sample_rate,
        n_fft=n_fft,
        hop_length=hop_length,
        win_length=win_length,
        n_mels=n_mels,
        fmin=f_min,
        fmax=f_max,
        power=1.0,
    )
    log_mel = np.log(np.clip(mel, a_min=1e-5, a_max=None))
    return log_mel.astype(np.float32)


def normalize_melspectrogram(
    mel: np.ndarray,
    method: str = "zscore",
    eps: float = 1e-8,
) -> np.ndarray:
    """Locally normalize a single mel-spectrogram using only its own statistics.

    This is *local* (per-spectrogram) normalization: each spectrogram is
    rescaled using statistics computed from itself alone, independent of any
    other file in the dataset. This differs from dataset-wide/global
    normalization, which would instead use statistics aggregated across many
    files (see ``preprocessing.preprocess.compute_npy_statistics``).

    Args:
        mel: A 2-D mel-spectrogram array of shape (n_mels, n_frames), e.g.
            as produced by ``audio_to_melspectrogram``.
        method: Normalization method to use:
            - ``"zscore"`` (default): ``(mel - mean) / (std + eps)``, using
              the spectrogram's own mean and standard deviation. Result has
              approximately zero mean and unit standard deviation.
            - ``"minmax"``: Rescales to the ``[0, 1]`` range using the
              spectrogram's own minimum and maximum values.
        eps: Small constant added to the denominator to avoid division by
            zero on constant/silent spectrograms.

    Returns:
        The normalized mel-spectrogram as a float32 array with the same
        shape as ``mel``.

    Raises:
        ValueError: If ``method`` is not one of ``"zscore"`` or ``"minmax"``.
    """
    mel = np.asarray(mel, dtype=np.float32)

    if method == "zscore":
        mean = np.mean(mel)
        std = np.std(mel)
        normalized = (mel - mean) / (std + eps)
    elif method == "minmax":
        mel_min = np.min(mel)
        mel_max = np.max(mel)
        normalized = (mel - mel_min) / (mel_max - mel_min + eps)
    else:
        raise ValueError(
            f"Unknown normalization method: '{method}'. Use 'zscore' or 'minmax'."
        )

    return normalized.astype(np.float32)


def denormalize_melspectrogram_with_stats(
    normalized_mel: np.ndarray,
    stats: dict,
    eps: float = 1e-8,
) -> np.ndarray:
    """Invert ``normalize_melspectrogram_with_stats``, returning to natural-log scale.

    IMPORTANT for vocoder inference: a model trained/sampling on normalized
    spectrograms (zero mean / unit std, or [0, 1]) outputs values on that
    *normalized* scale, not the natural-log mel scale a vocoder (e.g.
    HiFi-GAN, see ``vocoder.hifigan``) expects. Feeding un-denormalized
    (still normalized) spectrograms into a vocoder causes the audio to sound
    heavily distorted/clipped, because the vocoder interprets small
    normalized values (e.g. around 0) as if they were on the natural-log mel
    scale (where 0 means a mel energy of ``e^0 = 1``, already quite loud) --
    this is NOT a logarithmic dB scale, just a natural-log mel-energy scale
    with an epsilon floor (see ``audio_to_melspectrogram``), and it must be
    reconstructed exactly before synthesis.

    This function reverses the *same* fixed statistics used to normalize
    (e.g. from ``compute_global_mel_stats`` / saved via
    ``save_normalization_stats``), recovering the original natural-log
    mel-spectrogram:

        - zscore:  ``mel = normalized * (std + eps) + mean``
        - minmax:  ``mel = normalized * (max - min + eps) + min``

    Args:
        normalized_mel: A normalized mel-spectrogram (or a batch/segment of
            one), as produced by ``normalize_melspectrogram_with_stats`` or
            generated by a model trained on that normalized scale.
        stats: The exact same stats dict used for normalization: either
            ``{"method": "zscore", "mean": float, "std": float}`` or
            ``{"method": "minmax", "min": float, "max": float}``.
        eps: Must match the ``eps`` used during normalization.

    Returns:
        The denormalized mel-spectrogram, back on the natural-log mel scale
        (same scale/convention as ``audio_to_melspectrogram``'s output),
        ready to be exponentiated internally by a vocoder (e.g.
        ``vocoder.hifigan`` applies ``exp()``/expects this exact scale).

    Raises:
        ValueError: If ``stats["method"]`` is not one of ``"zscore"`` or ``"minmax"``.
    """
    normalized_mel = np.asarray(normalized_mel, dtype=np.float32)
    method = stats.get("method", "zscore")

    if method == "zscore":
        denormalized = normalized_mel * (stats["std"] + eps) + stats["mean"]
    elif method == "minmax":
        denormalized = normalized_mel * (stats["max"] - stats["min"] + eps) + stats["min"]
    else:
        raise ValueError(
            f"Unknown normalization method: '{method}'. Use 'zscore' or 'minmax'."
        )

    return denormalized.astype(np.float32)


def normalize_melspectrogram_with_stats(
    mel: np.ndarray,
    stats: dict,
    eps: float = 1e-8,
) -> np.ndarray:
    """Normalize a mel-spectrogram using externally supplied (e.g. global) statistics.

    Unlike ``normalize_melspectrogram``, which computes mean/std (or min/max)
    from ``mel`` itself, this applies a *fixed* set of statistics supplied by
    the caller. This matters when those statistics were computed once over an
    entire dataset (global normalization): because the same constant
    transform is applied everywhere, normalizing a full track and then
    slicing a fixed-size segment out of it gives an identical result to
    slicing first and normalizing the segment with the same stats -- i.e.
    the operation commutes with segmentation/windowing. Per-spectrogram
    normalization (``normalize_melspectrogram``) does not have this property,
    since each file's own mean/std would differ from any sub-segment's.

    Args:
        mel: A 2-D mel-spectrogram array of shape (n_mels, n_frames).
        stats: A dict describing the fixed statistics to apply. Either
            ``{"method": "zscore", "mean": float, "std": float}`` or
            ``{"method": "minmax", "min": float, "max": float}``.
        eps: Small constant added to the denominator to avoid division by zero.

    Returns:
        The normalized mel-spectrogram as a float32 array with the same
        shape as ``mel``.

    Raises:
        ValueError: If ``stats["method"]`` is not one of ``"zscore"`` or ``"minmax"``.
    """
    mel = np.asarray(mel, dtype=np.float32)
    method = stats.get("method", "zscore")

    if method == "zscore":
        normalized = (mel - stats["mean"]) / (stats["std"] + eps)
    elif method == "minmax":
        normalized = (mel - stats["min"]) / (stats["max"] - stats["min"] + eps)
    else:
        raise ValueError(
            f"Unknown normalization method: '{method}'. Use 'zscore' or 'minmax'."
        )

    return normalized.astype(np.float32)
